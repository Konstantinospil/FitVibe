const supported = new Set(["en", "de"]);
const languageEvent = "fitvibe-backoffice-language-changed";

export function activeLanguage(): string {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem("fitvibe:language")?.slice(0, 2).toLowerCase();
  const browser = window.navigator.language.slice(0, 2).toLowerCase();
  return supported.has(stored ?? "") ? (stored as string) : supported.has(browser) ? browser : "en";
}

export function setBackofficeLanguage(locale: string): void {
  if (!supported.has(locale)) throw new Error("Unsupported backoffice language");
  window.localStorage.setItem("fitvibe:language", locale);
  window.dispatchEvent(new Event(languageEvent));
}

function subscribe(callback: () => void): () => void {
  window.addEventListener("storage", callback);
  window.addEventListener(languageEvent, callback);
  return () => {
    window.removeEventListener("storage", callback);
    window.removeEventListener(languageEvent, callback);
  };
}

export function translate(key: string, values?: Record<string, string | number>, locale = activeLanguage()): string {
  const template = translations[locale]?.[key] ?? translations.en[key];
  if (template === undefined) throw new Error("Unknown Backoffice translation key: " + key);
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(values?.[name] ?? "{" + name + "}"));
}

export function useUiText(): (key: string, values?: Record<string, string | number>) => string {
  const language = useSyncExternalStore(subscribe, activeLanguage, () => "en");
  return (key, values) => translate(key, values, language);
}
